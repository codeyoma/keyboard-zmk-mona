#!/bin/bash
# Draw mona2_keymap.svg from the keymap with keymap-drawer (https://github.com/caksoylar/keymap-drawer).
set -euo pipefail
cd "$(dirname "$0")/.."

keymap -c keymap_drawer.config.yaml parse -c 11 -z config/mona2.keymap >mona2_keymap.yaml

# keymap-drawer does not draw encoders, so the wheel is drawn as one more, round key (keypos-42,
# styled in keymap_drawer.config.yaml): keymap-drawer/mona2_layout.dtsi is the shield's physical
# layout plus that key, and each layer gets the wheel's binding as its last legend.
uv run -q --with pyyaml python - <<'EOF'
import re
from pathlib import Path

import yaml

WHEEL_KEY = "            , <&key_physical_attrs  70  70  515  140       0     0     0>  // wheel\n"
WHEEL_LEGENDS = {"&inc_dec_kp C_VOL_UP C_VOL_DN": "Vol +/−"}

shield = Path("boards/shields/mona2/mona2.dtsi").read_text()
layout = re.search(r"physical_layout0: physical_layout_0 \{.*?\n    \};\n", shield, re.S).group(0)
layout = layout.replace("            ;\n", WHEEL_KEY + "            ;\n")
Path("keymap-drawer").mkdir(exist_ok=True)
Path("keymap-drawer/mona2_layout.dtsi").write_text(
    "// Generated by scripts/keymap.sh: the shield's physical layout plus the wheel, for drawing only.\n\n"
    "/ {\n" + layout + "};\n")

wheel = {}
for f in Path("config/layer").glob("*.dtsi"):
    text = f.read_text()
    label = re.search(r'label = "([^"]*)"', text).group(1)
    binding = re.search(r"sensor-bindings = <(.*?)>;", text)
    if binding:
        wheel[label] = WHEEL_LEGENDS.get(binding.group(1), binding.group(1))

keymap = yaml.safe_load(Path("mona2_keymap.yaml").read_text())
keymap["layout"] = {"dts_layout": "keymap-drawer/mona2_layout.dtsi"}
for label, keys in keymap["layers"].items():
    keys.append(wheel.get(label, {"t": "▽", "type": "trans"}))
Path("mona2_keymap.yaml").write_text(yaml.safe_dump(keymap, sort_keys=False, allow_unicode=True))
EOF

keymap -c keymap_drawer.config.yaml draw mona2_keymap.yaml >mona2_keymap.svg
